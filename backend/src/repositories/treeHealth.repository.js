const { query } = require('../config/db');

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

class TreeHealthRepository {
  /**
   * Finds a tree record by UUID or public Tree ID (ER-PLT-XXXXX).
   * @param {string} treeIdentifier
   * @returns {Promise<object|null>} Tree row or null
   */
  async findTreeByIdentifier(treeIdentifier) {
    let sql;
    let params;

    if (UUID_REGEX.test(treeIdentifier)) {
      sql = `
        SELECT id, tree_id, species, status, planted_on::text AS planted_on, contributor_id, created_at, updated_at
        FROM trees
        WHERE id = $1;
      `;
      params = [treeIdentifier];
    } else {
      sql = `
        SELECT id, tree_id, species, status, planted_on::text AS planted_on, contributor_id, created_at, updated_at
        FROM trees
        WHERE tree_id = $1;
      `;
      params = [treeIdentifier];
    }

    const res = await query(sql, params);
    return res.rows[0] || null;
  }

  /**
   * Inserts a new append-oriented health log record.
   * recorded_at and created_at are strictly generated by the database/server.
   * @param {object} params
   * @param {string} params.treeId - Tree internal UUID
   * @param {string} params.submittedBy - Caretaker user UUID from JWT
   * @param {string} params.healthStatus - Frozen health status enum
   * @param {string|null} [params.photoReference] - Photo path or reference
   * @param {string|null} [params.notes] - Caretaker notes
   * @returns {Promise<object>} Created health log row with join to tree and caretaker user
   */
  async createHealthLog({ treeId, submittedBy, healthStatus, photoReference = null, notes = null }) {
    const sql = `
      INSERT INTO health_logs (
        tree_id,
        submitted_by,
        health_status,
        photo_reference,
        notes,
        recorded_at,
        created_at
      )
      VALUES (
        $1,
        $2,
        $3,
        $4,
        $5,
        CURRENT_TIMESTAMP,
        CURRENT_TIMESTAMP
      )
      RETURNING id, tree_id, submitted_by, health_status, photo_reference, recorded_at, notes, created_at;
    `;
    const res = await query(sql, [treeId, submittedBy, healthStatus, photoReference, notes]);
    const inserted = res.rows[0];

    // Fetch user name and public tree_id for API response format
    const detailSql = `
      SELECT
        hl.id,
        hl.tree_id,
        t.tree_id AS public_tree_id,
        hl.health_status,
        hl.photo_reference,
        hl.notes,
        hl.recorded_at,
        hl.created_at,
        u.id AS submitted_by_id,
        u.name AS submitted_by_name
      FROM health_logs hl
      JOIN trees t ON hl.tree_id = t.id
      JOIN users u ON hl.submitted_by = u.id
      WHERE hl.id = $1;
    `;
    const detailRes = await query(detailSql, [inserted.id]);
    return detailRes.rows[0];
  }

  /**
   * Retrieves paginated health logs for a tree in newest-first chronological order.
   * @param {object} params
   * @param {string} params.treeId - Tree UUID
   * @param {number} [params.limit=20]
   * @param {number} [params.offset=0]
   * @returns {Promise<Array<object>>} List of health logs
   */
  async findHealthLogsByTreeId({ treeId, limit = 20, offset = 0 }) {
    const sql = `
      SELECT
        hl.id,
        hl.tree_id,
        t.tree_id AS public_tree_id,
        hl.health_status,
        hl.photo_reference,
        hl.notes,
        hl.recorded_at,
        hl.created_at,
        u.id AS submitted_by_id,
        u.name AS submitted_by_name
      FROM health_logs hl
      JOIN trees t ON hl.tree_id = t.id
      JOIN users u ON hl.submitted_by = u.id
      WHERE hl.tree_id = $1
      ORDER BY hl.recorded_at DESC, hl.created_at DESC, hl.id DESC
      LIMIT $2 OFFSET $3;
    `;
    const res = await query(sql, [treeId, limit, offset]);
    return res.rows;
  }

  /**
   * Counts total health logs for a tree.
   * @param {string} treeId - Tree UUID
   * @returns {Promise<number>} Total count
   */
  async countHealthLogsByTreeId(treeId) {
    const sql = `
      SELECT COUNT(*)::INTEGER AS total
      FROM health_logs
      WHERE tree_id = $1;
    `;
    const res = await query(sql, [treeId]);
    return res.rows[0]?.total || 0;
  }

  /**
   * Retrieves the most recent health observation for a tree to derive currentHealth.
   * @param {string} treeId - Tree UUID
   * @returns {Promise<object|null>} Latest health log or null
   */
  async findLatestHealthLog(treeId) {
    const sql = `
      SELECT
        id,
        health_status,
        photo_reference,
        notes,
        recorded_at,
        created_at
      FROM health_logs
      WHERE tree_id = $1
      ORDER BY recorded_at DESC, created_at DESC, id DESC
      LIMIT 1;
    `;
    const res = await query(sql, [treeId]);
    return res.rows[0] || null;
  }

  /**
   * Retrieves privacy-safe health history records for public profile embedding.
   * Strictly omits caretaker submitted_by user ID, email, and authentication details.
   * @param {string} treeId - Tree UUID
   * @param {number} [limit=20]
   * @returns {Promise<Array<object>>} Privacy-safe health history rows
   */
  async findPublicHealthHistory(treeId, limit = 20) {
    const sql = `
      SELECT
        id,
        health_status,
        photo_reference,
        notes,
        recorded_at
      FROM health_logs
      WHERE tree_id = $1
      ORDER BY recorded_at DESC, created_at DESC, id DESC
      LIMIT $2;
    `;
    const res = await query(sql, [treeId, limit]);
    return res.rows;
  }
}

module.exports = new TreeHealthRepository();
